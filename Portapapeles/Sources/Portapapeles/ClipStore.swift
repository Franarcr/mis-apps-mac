import AppKit
import CryptoKit

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    /// Texto copiado, rutas de archivo (una por línea) o descripción de la imagen.
    let text: String
    let hash: String
    var sourceApp: String?
    var date: Date
    var pinned = false
}

/// Vigila el portapapeles y guarda los últimos `limit` elementos (los fijados no cuentan).
@MainActor
final class ClipStore: ObservableObject {
    static let limit = 100

    /// Tipos que los gestores de contraseñas y otras apps marcan como privados o temporales.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false

    let folder: URL
    private var imagesFolder: URL { folder.appendingPathComponent("images") }
    private var historyFile: URL { folder.appendingPathComponent("history.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        folder = support.appendingPathComponent("Portapapeles")
        try? FileManager.default.createDirectory(at: folder.appendingPathComponent("images"), withIntermediateDirectories: true)
        load()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    // MARK: Lectura del portapapeles

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }

        let types = pb.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            add(kind: .files, text: paths, hashData: Data(paths.utf8), png: nil, app: app)
        } else if let string = pb.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(kind: .text, text: string, hashData: Data(string.utf8), png: nil, app: app)
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: data),
                  let png = rep.representation(using: .png, properties: [:]) {
            add(kind: .image, text: "Imagen \(rep.pixelsWide) × \(rep.pixelsHigh)", hashData: png, png: png, app: app)
        }
    }

    private func add(kind: ClipItem.Kind, text: String, hashData: Data, png: Data?, app: String?) {
        let hash = SHA256.hash(data: hashData).map { String(format: "%02x", $0) }.joined()

        // Si ya existe, solo lo sube al principio.
        if let index = items.firstIndex(where: { $0.hash == hash }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            existing.sourceApp = app ?? existing.sourceApp
            items.insert(existing, at: 0)
            save()
            return
        }

        let item = ClipItem(id: UUID(), kind: kind, text: text, hash: hash, sourceApp: app, date: Date())
        if let png {
            try? png.write(to: imageURL(item))
            writeThumbnail(png, to: thumbnailURL(item))
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        var unpinned = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned {
                kept.append(item)
            } else if unpinned < Self.limit {
                unpinned += 1
                kept.append(item)
            } else {
                deleteFiles(item)
            }
        }
        items = kept
    }

    // MARK: Acciones

    /// Pone el elemento en el portapapeles y lo sube al principio del historial.
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text, forType: .string)
        case .files:
            let urls = item.text.split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
            pb.writeObjects(urls)
        case .image:
            if let png = try? Data(contentsOf: imageURL(item)) {
                let pbItem = NSPasteboardItem()
                pbItem.setData(png, forType: .png)
                if let tiff = NSImage(data: png)?.tiffRepresentation { pbItem.setData(tiff, forType: .tiff) }
                pb.writeObjects([pbItem])
            }
        }
        lastChange = pb.changeCount
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// Deja en el portapapeles solo el texto de lo copiado (sin tipos de letra, colores ni enlaces).
    /// Devuelve false si lo copiado no es texto.
    func makePlainText() -> Bool {
        let pb = NSPasteboard.general
        guard let string = pb.string(forType: .string), !string.isEmpty else { return false }
        pb.clearContents()
        pb.setString(string, forType: .string)
        lastChange = pb.changeCount
        return true
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        trim()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(item)
        save()
    }

    /// Borra todo excepto los elementos fijados.
    func clear() {
        items.filter { !$0.pinned }.forEach(deleteFiles)
        items.removeAll { !$0.pinned }
        save()
    }

    // MARK: Imágenes

    func imageURL(_ item: ClipItem) -> URL { imagesFolder.appendingPathComponent("\(item.id.uuidString).png") }
    private func thumbnailURL(_ item: ClipItem) -> URL { imagesFolder.appendingPathComponent("\(item.id.uuidString)-mini.png") }

    func thumbnail(_ item: ClipItem) -> NSImage? {
        item.kind == .image ? NSImage(contentsOf: thumbnailURL(item)) : nil
    }

    private func writeThumbnail(_ png: Data, to url: URL) {
        guard let source = CGImageSourceCreateWithData(png as CFData, nil),
              let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceThumbnailMaxPixelSize: 96,
              ] as CFDictionary),
              let data = NSBitmapImageRep(cgImage: thumb).representation(using: .png, properties: [:]) else { return }
        try? data.write(to: url)
    }

    private func deleteFiles(_ item: ClipItem) {
        guard item.kind == .image else { return }
        try? FileManager.default.removeItem(at: imageURL(item))
        try? FileManager.default.removeItem(at: thumbnailURL(item))
    }

    // MARK: Persistencia

    private func load() {
        guard let data = try? Data(contentsOf: historyFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: historyFile, options: .atomic)
    }
}
