/// Comidas de todos los días que no son típicas ticas: comida rápida, snacks, postres, bebidas y licores.
/// Valores de referencia del USDA (FoodData Central: SR Legacy y FNDDS) y, en las cadenas, de la información
/// nutricional que publica cada una. Son aproximados: el tamaño y la receta cambian de un local a otro.
/// Van con `source` «tico» igual que las comidas típicas: vienen con la app y no se guardan aparte.
enum CommonFoods {
    /// Valores por 100 g (o 100 ml en bebidas).
    private static func f(_ name: String, _ kcal: Double, _ p: Double, _ c: Double, _ fat: Double, sat: Double? = nil,
                          fib: Double? = nil, sug: Double? = nil, na: Double? = nil, drink: Bool = false,
                          _ portions: [(String, Double)]) -> Food {
        Food(id: "comun-" + slug(name), name: name,
             per100: Nutrients(kcal: kcal, protein: p, carbs: c, fat: fat, saturated: sat, fiber: fib, sugar: sug, sodium: na),
             portions: portions.map { Portion(name: $0.0, grams: $0.1) }, isDrink: drink)
    }

    /// Valores de una unidad completa (como los publica cada cadena) que pesa `grams`; se pasan a 100 g.
    private static func u(_ name: String, _ grams: Double, _ kcal: Double, _ p: Double, _ c: Double, _ fat: Double,
                          sat: Double? = nil, fib: Double? = nil, sug: Double? = nil, na: Double? = nil,
                          drink: Bool = false, unit: String = "1 unidad") -> Food {
        let k = 100 / grams
        return f(name, kcal * k, p * k, c * k, fat * k, sat: sat.map { $0 * k }, fib: fib.map { $0 * k },
                 sug: sug.map { $0 * k }, na: na.map { $0 * k }, drink: drink, [(unit, grams)])
    }

    private static func slug(_ s: String) -> String {
        s.folding(options: .diacriticInsensitive, locale: nil).lowercased()
            .map { $0.isLetter || $0.isNumber ? String($0) : "-" }.joined()
    }

